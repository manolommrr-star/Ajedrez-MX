/**
 * Codificador UTF-8 → Windows-1252 (ANSI de Windows, "Latin-1 suplementario").
 *
 * Swiss Manager es un programa Windows clásico: espera archivos ANSI.
 * Un archivo UTF-8 sin BOM muestra "Ramírez" como "RamÃ­rez"; con BOM,
 * algunos importadores antiguos rompen la primera celda. La solución
 * robusta es generar el archivo ya codificado en cp1252.
 *
 * Tabla completa de mapeo para el rango Latin-1 (U+00A0–U+00FF) más los
 * signos comunes del español. Cualquier carácter fuera de la tabla se
 * reemplaza por '?' (el asistente de Swiss Manager lo conserva).
 */

/** Bytes cp1252 para caracteres Latin-1 (índice = codePoint - 0xA0). */
const LATIN1 = [
  0xA0, 0xA1, 0xA2, 0xA3, 0xA4, 0xA5, 0xA6, 0xA7, 0xA8, 0xA9, 0xAA, 0xAB, 0xAC, 0xAD, 0xAE, 0xAF,
  0xB0, 0xB1, 0xB2, 0xB3, 0xB4, 0xB5, 0xB6, 0xB7, 0xB8, 0xB9, 0xBA, 0xBB, 0xBC, 0xBD, 0xBE, 0xBF,
  0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7, 0xC8, 0xC9, 0xCA, 0xCB, 0xCC, 0xCD, 0xCE, 0xCF,
  0xD0, 0xD1, 0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xD7, 0xD8, 0xD9, 0xDA, 0xDB, 0xDC, 0xDD, 0xDE, 0xDF,
  0xE0, 0xE1, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6, 0xE7, 0xE8, 0xE9, 0xEA, 0xEB, 0xEC, 0xED, 0xEE, 0xEF,
  0xF0, 0xF1, 0xF2, 0xF3, 0xF4, 0xF5, 0xF6, 0xF7, 0xF8, 0xF9, 0xFA, 0xFB, 0xFC, 0xFD, 0xFE, 0xFF
];

/** Caracteres especiales de cp1252 fuera de Latin-1 (curly quotes, guiones). */
const EXTRAS = new Map([
  [0x20AC, 0x80], [0x201A, 0x82], [0x0192, 0x83], [0x201E, 0x84], [0x2026, 0x85],
  [0x2020, 0x86], [0x2021, 0x87], [0x02C6, 0x88], [0x2030, 0x89], [0x0160, 0x8A],
  [0x2039, 0x8B], [0x0152, 0x8C], [0x017D, 0x8E], [0x2018, 0x91], [0x2019, 0x92],
  [0x201C, 0x93], [0x201D, 0x94], [0x2022, 0x95], [0x2013, 0x96], [0x2014, 0x97],
  [0x02DC, 0x98], [0x2122, 0x99], [0x0161, 0x9A], [0x203A, 0x9B], [0x0153, 0x9C],
  [0x017E, 0x9E], [0x0178, 0x9F]
]);

/** ¿Puede representarse el carácter en cp1252? */
export function esRepresentable(cp) {
  if (cp < 0x80) return true; // ASCII
  if (cp >= 0xA0 && cp <= 0xFF) return true; // Latin-1
  return EXTRAS.has(cp);
}

/** Convierte un string UTF-8 a un Uint8Array en codificación Windows-1252. */
export function aCp1252(texto) {
  const bytes = [];
  for (const ch of String(texto ?? '')) {
    const cp = ch.codePointAt(0);
    if (cp < 0x80) {
      bytes.push(cp);
    } else if (cp >= 0xA0 && cp <= 0xFF) {
      bytes.push(LATIN1[cp - 0xA0]);
    } else if (EXTRAS.has(cp)) {
      bytes.push(EXTRAS.get(cp));
    } else {
      bytes.push(0x3F); // '?' para lo no representable
    }
  }
  return new Uint8Array(bytes);
}
